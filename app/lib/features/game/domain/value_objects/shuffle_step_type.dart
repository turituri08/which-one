/// シャッフルタイムラインを構成する動作プリミティブの種別。
enum ShuffleStepType {
  /// 移動：直線、曲線、円弧、上下移動。
  move,

  /// 停止：短い静止でリズムを切る。
  pause,

  /// 交差：前後または左右の手が重なる。
  cross,

  /// 受け渡し：2本の手の接触を伴ってコイン保持手を変更する。
  ///
  /// コイン保持手を変更できるのはこの種別だけである。
  transfer,

  /// フェイント：接触や投擲に見えるが、保持手を変更しない。
  feint,

  /// 画面外移動：画面端へ抜ける、または背後方向へ移る。
  exitStage,

  /// 再出現：画面外手掛かりの後、別位置から手が現れる。
  enterStage,
}
