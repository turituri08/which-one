/// ゲーム進行の状態機械。
enum GamePhase {
  /// タイトル・開始待ち。
  idle,

  /// コイン保持手を明確に示す確認フェーズ。入力は受け付けない。
  confirming,

  /// シャッフルタイムラインを実行するフェーズ。入力は受け付けない。
  shuffling,

  /// 手へのタップと制限時間を受け付けるフェーズ。
  answering,

  /// 正解演出、レベル加算、次問準備を行うフェーズ。
  correct,

  /// 選択位置と正解位置を明示するフェーズ。
  incorrect,

  /// 最高到達レベル、正解位置、遷移操作を表示するフェーズ。
  result,

  /// 非アクティブ化前の進行状態と残り時間を保持するフェーズ。
  paused,
}
